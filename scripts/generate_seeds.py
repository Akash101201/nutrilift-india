def build_foods() -> list[dict]:
    foods = []
    for row in CORE_FOODS:
        foods.append({
            "id": row[0],
            "name": row[1],
            "transliterations": row[2],
            "servingUnit": row[3],
            "servingAmount": row[4],
            "gramsPerServing": row[5],
            "calories": row[6],
            "proteinG": row[7],
            "carbG": row[8],
            "fatG": row[9],
            "source": row[10],
            "confidence": row[11],
        })

    n = 0
    while len(foods) < 320:
        cat_id, cat_name, unit, grams, macros = CATEGORIES[n % len(CATEGORIES)]
        region = REGIONAL[n % len(REGIONAL)]
        variant = (n // len(CATEGORIES)) + 1
        cal, p, c, f = macros(variant)
        fid = f"{cat_id}_{region.lower().replace('-', '_').replace(' ', '_')}_{variant}"
        foods.append({
            "id": fid,
            "name": f"{region} {cat_name} {variant}",
            "transliterations": [cat_name.lower()],
            "servingUnit": unit,
            "servingAmount": 1,
            "gramsPerServing": grams,
            "calories": float(cal),
            "proteinG": float(p),
            "carbG": float(c),
            "fatG": float(f),
            "source": "estimated",
            "confidence": "low",
        })
        n += 1
    return foods


